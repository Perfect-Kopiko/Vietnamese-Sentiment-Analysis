"""
Script đọc toàn bộ các file kết quả JSON trong thư mục results/ để tổng hợp:
1. In bảng so sánh định dạng đẹp trên Terminal.
2. Tự động sinh mã bảng chuẩn LaTeX (định dạng 2 cột hội nghị ACL với booktabs)
   và tự động in đậm (\textbf{...}) giá trị tốt nhất ở mỗi cột chỉ số.
3. Lưu bảng vào file results/summary_table.tex.
"""

import glob
import json
import os
import sys
from typing import Any, Dict, List, Optional


def load_all_results(results_dir: str = "results") -> List[Dict[str, Any]]:
    """Đọc và sắp xếp toàn bộ file json trong thư mục results."""
    if not os.path.exists(results_dir):
        return []

    pattern = os.path.join(results_dir, "*.json")
    json_files = sorted(glob.glob(pattern))

    records = []
    for fpath in json_files:
        try:
            with open(fpath, "r", encoding="utf-8") as f:
                data = json.load(f)

            run_name = data.get("run_name", os.path.splitext(os.path.basename(fpath))[0])
            config = data.get("config", {})
            data_cfg = config.get("data", {})
            model_cfg = config.get("model", {})
            embed_cfg = config.get("embedding", {})
            train_cfg = config.get("training", {})
            test_metrics = data.get("test_metrics", {})

            # Trích xuất cấu hình
            use_seg = data_cfg.get("use_word_segment", True)
            norm_noise = data_cfg.get("normalize_noise", False)
            pooling = model_cfg.get("pooling", "attention")
            w2v_path = embed_cfg.get("w2v_path", "")
            has_w2v = bool(w2v_path and str(w2v_path).strip())
            loss_type = train_cfg.get("loss_type", "ce")

            # Trích xuất chỉ số test
            acc = float(test_metrics.get("accuracy", 0.0)) * 100
            macro_f1 = float(test_metrics.get("macro_f1", 0.0)) * 100
            weighted_f1 = float(test_metrics.get("weighted_f1", 0.0)) * 100
            f1_neg = float(test_metrics.get("f1_negative", 0.0)) * 100
            f1_neu = float(test_metrics.get("f1_neutral", 0.0)) * 100
            f1_pos = float(test_metrics.get("f1_positive", 0.0)) * 100

            records.append({
                "file": os.path.basename(fpath),
                "run_name": run_name,
                "use_seg": "Yes" if use_seg else "No",
                "norm_noise": "Yes" if norm_noise else "No",
                "has_w2v": "Yes" if has_w2v else "No",
                "pooling": pooling,
                "loss_type": loss_type,
                "acc": acc,
                "macro_f1": macro_f1,
                "weighted_f1": weighted_f1,
                "f1_neg": f1_neg,
                "f1_neu": f1_neu,
                "f1_pos": f1_pos
            })
        except Exception as exc:
            print(f"[!] Lỗi khi đọc file {fpath}: {exc}")

    return records


def print_ascii_table(records: List[Dict[str, Any]]) -> None:
    """In bảng so sánh định dạng đẹp ra terminal."""
    header = (
        f"{'Run Name':<28} | {'Seg':<4} | {'Noise':<5} | {'W2V':<4} | {'Loss':<11} | "
        f"{'Acc (%)':<8} | {'Macro-F1':<8} | {'F1-Neg':<7} | {'F1-Neu':<7} | {'F1-Pos':<7}"
    )
    separator = "-" * len(header)

    print("\n" + "=" * len(header))
    print("  BẢNG TỔNG HỢP KẾT QUẢ THỰC NGHIỆM TRÊN TẬP KIỂM TRA (TEST SET)")
    print("=" * len(header))
    print(header)
    print(separator)

    for r in records:
        print(
            f"{r['run_name']:<28} | {r['use_seg']:<4} | {r['norm_noise']:<5} | {r['has_w2v']:<4} | {r['loss_type']:<11} | "
            f"{r['acc']:>7.2f}% | {r['macro_f1']:>7.2f}% | {r['f1_neg']:>6.2f}% | {r['f1_neu']:>6.2f}% | {r['f1_pos']:>6.2f}%"
        )
    print(separator + "\n")


def generate_latex_table(records: List[Dict[str, Any]], output_path: str = "results/summary_table.tex") -> str:
    """
    Sinh bảng LaTeX định dạng ACL chuẩn 2 cột sử dụng booktabs.
    Tự động in đậm (\\textbf{...}) giá trị lớn nhất ở từng cột chỉ số.
    """
    if not records:
        return ""

    # Tìm giá trị lớn nhất ở mỗi cột để in đậm
    max_acc = max(r["acc"] for r in records)
    max_macro = max(r["macro_f1"] for r in records)
    max_neg = max(r["f1_neg"] for r in records)
    max_neu = max(r["f1_neu"] for r in records)
    max_pos = max(r["f1_pos"] for r in records)

    def _format_cell(val: float, max_val: float) -> str:
        # Làm tròn 2 chữ số thập phân khi so sánh
        if abs(val - max_val) < 1e-4:
            return f"\\textbf{{{val:.2f}}}"
        return f"{val:.2f}"

    lines = []
    lines.append("% --- ACL format comparison table generated by reproduce_results.py ---")
    lines.append("\\begin{table*}[t]")
    lines.append("\\centering")
    lines.append("\\small")
    lines.append("\\begin{tabular}{l ccccc ccccc}")
    lines.append("\\toprule")
    lines.append(
        "\\textbf{Model / Configuration} & "
        "\\textbf{Seg} & \\textbf{Noise} & \\textbf{W2V} & \\textbf{Loss} & "
        "\\textbf{Acc (\\%)} & \\textbf{Macro-F1 (\\%)} & \\textbf{F1-Neg} & \\textbf{F1-Neu} & \\textbf{F1-Pos} \\\\"
    )
    lines.append("\\midrule")

    for r in records:
        name_clean = r["run_name"].replace("_", "\\_")
        loss_clean = r["loss_type"].replace("_", "\\_")
        c_acc = _format_cell(r["acc"], max_acc)
        c_macro = _format_cell(r["macro_f1"], max_macro)
        c_neg = _format_cell(r["f1_neg"], max_neg)
        c_neu = _format_cell(r["f1_neu"], max_neu)
        c_pos = _format_cell(r["f1_pos"], max_pos)

        lines.append(
            f"{name_clean} & {r['use_seg']} & {r['norm_noise']} & {r['has_w2v']} & {loss_clean} & "
            f"{c_acc} & {c_macro} & {c_neg} & {c_neu} & {c_pos} \\\\"
        )

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append(
        "\\caption{Comparison of BiLSTM configurations on Vietnamese Students' Feedback Dataset (UIT-VSFC) test set. "
        "Bold indicates the best score in each metric.}"
    )
    lines.append("\\label{tab:bilstm_results}")
    lines.append("\\end{table*}")

    latex_code = "\n".join(lines) + "\n"

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(latex_code)

    print(f"[+] Đã tạo file bảng LaTeX ACL tại: {output_path}")
    return latex_code


def main():
    project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    results_dir = os.path.join(project_root, "results")
    tex_path = os.path.join(results_dir, "summary_table.tex")

    records = load_all_results(results_dir)

    if not records:
        print("\n" + "=" * 65)
        print("  [!] CHƯA TÌM THẤY KẾT QUẢ THỰC NGHIỆM TRONG THƯ MỤC 'results/'")
        print("=" * 65)
        print("Hướng dẫn chạy thực nghiệm:")
        print("1. Huấn luyện thử nghiệm nhanh BiLSTM:")
        print("   python scripts/train_bilstm.py --epochs 2 --run_name test_run --no_wandb")
        print("2. Hoặc chạy trên Kaggle GPU qua notebook:")
        print("   notebooks/03_train_bilstm_kaggle.ipynb")
        print("3. Sau khi có file .json trong results/, chạy lại lệnh này:")
        print("   python scripts/reproduce_results.py")
        print("=" * 65 + "\n")
        return

    # In bảng ra terminal
    print_ascii_table(records)

    # Sinh mã LaTeX
    generate_latex_table(records, output_path=tex_path)


if __name__ == "__main__":
    main()
